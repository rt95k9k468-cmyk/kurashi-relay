#!/usr/bin/env bash
# =========================================================
#  くらしノートの中継所を建てる（パソコンがある場合）
# =========================================================
#
#  iPhoneしか無いなら、これは要りません。アプリの
#  設定 → ダイエット → 中継所 に、ボタンだけで終わる道があります。
#
#  使い方（この relay/ フォルダの中で）:
#
#      ./setup.sh
#
#  すること:
#    1. 当てられない道（合言葉）を作って、Secret として置く
#    2. 公開する（KVの置き場は Cloudflare が自分で作ります）
#    3. 本当に置けて取れるかを、その場で確かめる
#    4. アプリに貼るURLを出す
#
#  要るもの: Node（npx が使えれば十分）と、Cloudflareの無料アカウント。
#  ログインしていなければ、途中でブラウザが開きます。

set -euo pipefail
cd "$(dirname "$0")"

WRANGLER="npx --yes wrangler@4"
say() { printf '\n\033[1m%s\033[0m\n' "$*"; }
die() { printf '\n\033[31m%s\033[0m\n' "$*" >&2; exit 1; }

command -v npx >/dev/null || die "npx が見つかりません。Node を入れてください（https://nodejs.org）"

# --- 1. 道（合言葉）------------------------------------------------------
# 人が考える「ランダム」はランダムではないので、機械に作らせます。
# 紛らわしい四文字（l 1 o 0）を落とすと、ちょうど32文字になります。
say "道を作って、Secret として置きます…"
secret=$(LC_ALL=C tr -dc 'abcdefghijkmnpqrstuvwxyz23456789' </dev/urandom | head -c 16)
relay_path="/kn-$secret"
printf '%s' "$relay_path" | $WRANGLER secret put RELAY_PATH \
  || die "Secret を置けませんでした（ログインできていない可能性があります）"
say "道: $relay_path"

# --- 2. 公開 -------------------------------------------------------------
# KV の置き場は wrangler.jsonc に id を書いていないので、Cloudflare が
# 作って結びます（作ったあと、id は wrangler.jsonc に書き戻されます）。
say "公開します…"
deploy_out=$($WRANGLER deploy 2>&1) || { echo "$deploy_out"; die "公開できませんでした"; }
echo "$deploy_out"

base=$(printf '%s' "$deploy_out" | grep -oE 'https://[a-z0-9.-]+\.workers\.dev' | head -1)
[ -n "$base" ] || die "公開はできたようですが、URLを読み取れませんでした。上の出力を見て、手で組み立ててください。"
url="$base$relay_path"

# --- 3. 本当に動くか -----------------------------------------------------
say "置けて取れるか、確かめます…"
./verify.sh "$url" || die "確認に失敗しました。上の理由を見てください。"

# --- 4. アプリへ ---------------------------------------------------------
cat <<EOS

════════════════════════════════════════════════════════════
 中継所ができました。

   $url

 これを、くらしノートの
   設定 → ダイエット → 中継所
 の「中継所のURL」に貼って「保存」してください。

 そのあとショートカットの最後を「クリップボードにコピー」から
 「URLの内容を取得」に差し替えます（方法=POST、本文を要求=ファイル、
 ファイル=一つ前の「テキスト」の結果）。URLは上と同じものです。

 くわしくは relay/README.md の「ショートカットを直す」を。
════════════════════════════════════════════════════════════

EOS
